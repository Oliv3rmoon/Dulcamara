#!/usr/bin/env python3
"""Regenerate the executable's recovery font from the unmodified, OFL-licensed Inter face."""
from pathlib import Path

root = Path(__file__).resolve().parents[1]
data = (root / "assets/fonts/Inter-400.ttf").read_bytes()
with (root / "src/ui/inter_regular.inc").open("w", newline="\n") as output:
    output.write("/* Generated by tools/embed-ui-font.py; Inter Project Authors, SIL OFL 1.1. */\n")
    for start in range(0, len(data), 24):
        output.write("    " + ", ".join(f"0x{byte:02x}" for byte in data[start:start+24]) + ",\n")
